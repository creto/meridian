#!/usr/bin/env node
/**
 * meridian create-component MyComponent
 * Writes the scaffold next to this script's invocation directory under plugins/.
 * Refuses names that are not PascalCase.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

const name = process.argv[2];
if (!name || !/^[A-Z][A-Za-z0-9]{1,40}$/.test(name)) {
  console.error("Usage: node scripts/create-component.mjs MyComponent");
  process.exit(1);
}
if (name.includes("..") || name.includes("/") || name.includes("\\")) {
  console.error("Refusing a path-like component name");
  process.exit(1);
}

const type = name.replace(/[A-Z]/g, (letter, index) => (index ? "-" : "") + letter.toLowerCase()).replace(/^-/, "");
const files = {
  [`${name}.definition.ts`]: `export const ${name}Definition = { type: "${type}", title: "${name}", group: "custom" } as const;\n`,
  [`${name}.validator.ts`]: `export function validate${name}(value: unknown): string | null {\n  if (typeof value !== "string" || !value.trim()) return "${name} is required";\n  return null;\n}\n`,
  [`${name}.register.ts`]: `export function register${name}(plugins: { register: (def: { type: string }) => void }) {\n  plugins.register({ type: "${type}" });\n}\n`,
  ["README.md"]: `# ${name}\n\nGenerated by scripts/create-component.mjs.\nThis plugin is not loaded until a tenant allowlist includes plugin_${type}.\n`,
};

const dir = join(process.cwd(), "plugins", name);
await mkdir(dir, { recursive: true });
for (const [file, body] of Object.entries(files)) {
  await writeFile(join(dir, file), body, "utf8");
}
console.log(JSON.stringify({ dir, files: Object.keys(files) }));
